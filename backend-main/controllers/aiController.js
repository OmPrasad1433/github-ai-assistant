// 5. AI Chat Assistant
async function chatAssistant(req, res) {
  const { messages, repoName, description, files = [], activeFileContext } = req.body;
  if (!Array.isArray(messages)) {
    return res.status(400).json({ error: "Messages must be an array." });
  }

  const recentMessages = messages.slice(-10);
  const safeActiveFile = activeFileContext
    ? {
        name: truncateText(activeFileContext.name, 200),
        content: truncateText(activeFileContext.content, 6000),
      }
    : null;

  // We build a context-aware system prompt
  const systemPrompt = `
You are GitHub Copilot, a senior developer AI assistant integrated into "GitHub AI", a premium MERN GitHub application.
Current Repository: ${repoName}
Repository Description: ${description || "No description provided."}
Repository Files Structure:
${files.slice(0, 300).map(f => `- ${f}`).join("\n")}

${safeActiveFile ? `Active File Open: ${safeActiveFile.name}\nActive File Code:\n\`\`\`\n${safeActiveFile.content}\n\`\`\`` : "No file is currently selected/open in the code viewer."}

Your job is to answer user queries with expert precision, provide readable code snippets, explain the workspace structure, detect bugs, or generate code/documentation.
Always reply in clean GitHub Flavored Markdown. Be concise, professional, and friendly.
`;

  // We build a chat history
  const prompt = `${systemPrompt}\n\nChat History:\n${recentMessages.map(m => `${m.role === "user" ? "User" : "Assistant"}: ${truncateText(m.content, 1500)}`).join("\n")}\n\nAssistant:`;

  try {
    const reply = await callLLM(prompt);
    res.json({ reply });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
}

