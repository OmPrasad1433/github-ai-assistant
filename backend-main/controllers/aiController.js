const dotenv = require("dotenv");
dotenv.config();

const AI_TIMEOUT_MS = Number(process.env.AI_TIMEOUT_MS) || 20000;
const MAX_PROMPT_CHARS = Number(process.env.AI_MAX_PROMPT_CHARS) || 12000;

function truncateText(value, maxLength = MAX_PROMPT_CHARS) {
  const text = String(value || "");
  return text.length > maxLength ? `${text.slice(0, maxLength)}\n\n[Content truncated for AI request size.]` : text;
}

async function fetchWithTimeout(url, options) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), AI_TIMEOUT_MS);

  try {
    return await fetch(url, { ...options, signal: controller.signal });
  } finally {
    clearTimeout(timeout);
  }
}

function normalizeAIText(value, fallback = "No response generated by AI.") {
  const text = String(value || "").trim();
  return text || fallback;
}

function getGeminiText(data) {
  const text = data?.candidates
    ?.flatMap((candidate) => candidate?.content?.parts || [])
    ?.map((part) => part?.text)
    ?.filter(Boolean)
    ?.join("\n");

  if (text) {
    return normalizeAIText(text);
  }

  const finishReason = data?.candidates?.[0]?.finishReason;
  if (finishReason) {
    return `No text response generated by Gemini. Finish reason: ${finishReason}.`;
  }

  return "No response generated by AI.";
}

function getGeminiModelName() {
  const model = process.env.GEMINI_MODEL?.trim();
  if (!model) {
    throw new Error("GEMINI_MODEL is not configured. Set it to a supported Gemini model in the backend `.env` file.");
  }

  return model.startsWith("models/") ? model : `models/${model}`;
}

// Helper to make API requests to the LLM
async function callLLM(prompt) {
  const provider = process.env.AI_PROVIDER || "gemini";
  const safePrompt = truncateText(prompt);

  if (provider === "gemini") {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey || apiKey === "your_gemini_api_key_here") {
      return "⚠️ **Gemini API Key is missing or invalid.** Please set a valid `GEMINI_API_KEY` in the backend `.env` file to enable AI capabilities.";
    }

    try {
      const modelName = getGeminiModelName();
      const response = await fetchWithTimeout(
        `https://generativelanguage.googleapis.com/v1beta/${modelName}:generateContent?key=${apiKey}`,
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            contents: [{ parts: [{ text: safePrompt }] }],
            generationConfig: {
              temperature: 0.2,
              maxOutputTokens: 2048,
            }
          }),
        }
      );

      const data = await response.json();
      if (!response.ok) {
        throw new Error(data.error?.message || "Gemini API error");
      }

      return getGeminiText(data);
    } catch (err) {
      console.error("Gemini API Request Failed:", err);
      return err.name === "AbortError"
        ? "AI service timed out. Please try again with a smaller request."
        : `AI service error: ${err.message}`;
    }
  } else if (provider === "openai") {
    const apiKey = process.env.OPENAI_API_KEY;
    if (!apiKey || apiKey === "your_openai_api_key_here") {
      return "⚠️ **OpenAI API Key is missing or invalid.** Please set a valid `OPENAI_API_KEY` in the backend `.env` file.";
    }

    try {
      const response = await fetchWithTimeout("https://api.openai.com/v1/chat/completions", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${apiKey}`,
        },
        body: JSON.stringify({
          model: "gpt-4o-mini",
          messages: [{ role: "user", content: safePrompt }],
          temperature: 0.2,
          max_tokens: 2048,
        }),
      });

      const data = await response.json();
      if (!response.ok) {
        throw new Error(data.error?.message || "OpenAI API error");
      }

      return normalizeAIText(data.choices?.[0]?.message?.content);
    } catch (err) {
      console.error("OpenAI API Request Failed:", err);
      return err.name === "AbortError"
        ? "AI service timed out. Please try again with a smaller request."
        : `AI service error: ${err.message}`;
    }
  } else {
    return `Unsupported AI Provider: "${provider}". Supported values are "gemini" or "openai".`;
  }
}

// 1. AI README Generator
async function generateReadme(req, res) {
  const { repoName, description, languages = [], tags = [] } = req.body;
  if (!repoName || typeof repoName !== "string") {
    return res.status(400).json({ error: "Repository name is required." });
  }

  const prompt = `
You are a senior technical writer. Generate a professional, comprehensive, and clean GitHub README.md file for a project with the following details:
- Project Name: ${repoName}
- Description: ${description || "No description provided."}
- Languages used: ${languages.join(", ") || "Not specified"}
- Tags/Topics: ${tags.join(", ") || "Not specified"}

The README should include:
- A beautiful header with name and brief description
- Clear Features list
- Installation steps (assume standard node/npm setups unless languages dictate otherwise)
- Basic Usage examples
- Clean tables or badges where applicable
- Professional formatting in standard GitHub Flavored Markdown (do not wrap in a markdown block, just output the raw markdown text itself).
`;

  try {
  const readme = await callLLM(prompt);
    res.json({ readme });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
}

// 2. AI Commit Message Generator
async function generateCommitMessage(req, res) {
  const { codeChanges, filename } = req.body;
  if (!codeChanges || typeof codeChanges !== "string") {
    return res.status(400).json({ error: "Code changes are required." });
  }

  const prompt = `
You are a helpful software engineer. Write a concise, meaningful, and professional Git commit message following conventional commits style (e.g. feat: add file explorer, fix: repair authentication token) based on these changes:
File: ${filename || "Multiple files"}
Changes/Code Diff:
${truncateText(codeChanges, 4000)}

Provide exactly ONE commit message option. Do not add explanations, quotes, bullet points, or introductory text. Just output the single-line commit message.
`;

  try {
    const commitMessage = await callLLM(prompt);
    res.json({ commitMessage: commitMessage.trim().replace(/^['"`]|['"`]$/g, "") });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
}

